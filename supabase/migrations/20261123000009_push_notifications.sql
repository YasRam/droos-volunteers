-- Phone (Web Push) notifications.
-- Every row added to public.notifications is also sent to the recipient's phones/browsers
-- that turned notifications on. The send-push edge function does the sending; this file
-- stores the subscriptions and calls the function after each insert.

create extension if not exists pg_net with schema extensions;

-- ---------------------------------------------------------------------
-- One row per phone/browser that turned notifications on.
-- ---------------------------------------------------------------------
create table public.push_subscriptions (
  endpoint      text primary key,
  email         extensions.citext not null default app.email(),
  p256dh        text not null,
  auth          text not null,
  user_agent    text,
  created_at    timestamptz not null default now(),
  last_sent_at  timestamptz
);
create index push_subscriptions_email_idx on public.push_subscriptions (email);

alter table public.push_subscriptions enable row level security;

create policy push_subscriptions_own on public.push_subscriptions
  for all to authenticated
  using (email = (select app.email()))
  with check (email = (select app.email()));

grant select, insert, update, delete on public.push_subscriptions to authenticated;

-- ---------------------------------------------------------------------
-- Server-only settings. No policies: only the edge function (service role) reads it.
-- The VAPID keys are generated by the function itself on its first run, so no secret
-- ever has to be copied by hand. hook_secret proves a call came from this database.
-- ---------------------------------------------------------------------
create table public.push_config (
  id             boolean primary key default true check (id),
  function_url   text not null,
  function_auth  text not null,   -- the project's public anon key (not a secret)
  hook_secret    text not null default encode(extensions.gen_random_bytes(32), 'hex'),
  vapid_subject  text not null default 'https://yasram.github.io/droos-volunteers/',
  vapid_public   text,
  vapid_private  text
);
alter table public.push_config enable row level security;
revoke all on public.push_config from anon, authenticated;

