-- ---------------------------------------------------------------------
-- After each statement that adds notifications: one call with all the new ids.
-- pg_net queues the request and returns at once; a failure never blocks the insert.
-- ---------------------------------------------------------------------
create or replace function app.push_new_notifications()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  cfg public.push_config;
  ids jsonb;
begin
  select * into cfg from public.push_config where id;
  select jsonb_agg(n.id) into ids
  from new_rows n
  where exists (select 1 from public.push_subscriptions s where s.email = n.recipient_email);
  if cfg is null or ids is null then
    return null;
  end if;
  perform net.http_post(
    url := cfg.function_url,
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'Authorization', 'Bearer ' || cfg.function_auth,
      'x-push-secret', cfg.hook_secret
    ),
    body := jsonb_build_object('ids', ids),
    timeout_milliseconds := 8000
  );
  return null;
exception when others then
  raise warning 'push not queued: %', sqlerrm;
  return null;
end;
$$;

drop trigger if exists notifications_push on public.notifications;
create trigger notifications_push
  after insert on public.notifications
  referencing new table as new_rows
  for each statement execute function app.push_new_notifications();

-- Lets the app (and Claude) ask the function to set itself up: generate the keys and
-- publish the public one in app_settings. Needs the settings permission.
create or replace function public.push_setup()
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  cfg public.push_config;
begin
  if not (app.has_perm('settings.manage') or app.is_internal()) then
    raise exception 'محتاج صلاحية الإعدادات' using errcode = '42501';
  end if;
  select * into cfg from public.push_config where id;
  return net.http_post(
    url := cfg.function_url,
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'Authorization', 'Bearer ' || cfg.function_auth,
      'x-push-secret', cfg.hook_secret
    ),
    body := jsonb_build_object('ids', '[]'::jsonb)
  );
end;
$$;
