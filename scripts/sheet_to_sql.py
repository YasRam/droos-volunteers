#!/usr/bin/env python3
"""
Convert the Google Sheet export (xlsx) into one SQL file that loads every
tab into the Supabase schema.

    python3 scripts/sheet_to_sql.py data/source/sheet.xlsx data/seed_data.sql

The SQL runs as the table owner (postgres) with user triggers disabled, so no
notifications or audit rows are created for history. Everything a trigger would derive (birth date, gender,
companion rows) is computed here instead. A report of anything that needed
fixing is written next to the SQL file.
"""
import datetime as dt
import json
import re
import sys
import uuid

import openpyxl

STATUSES = {'تحت المتابعة', 'مشروع مسئول', 'مسئول', 'مدرب', 'خارج المتابعة'}
ACCEPTANCE = {'اختبار', 'مقبول', 'رفض الانترفيو', 'مرفوض', 'معتذر', 'معتذر نهائى', 'مفصول'}
REQUEST = {'مقبول': 'accepted', 'في انتظار الموافقة': 'pending', 'مرفوض': 'rejected'}
DAYS = ['السبت', 'الأحد', 'الاثنين', 'الثلاثاء', 'الأربعاء', 'الخميس', 'الجمعة']
TABLES = ['lookups', 'staff_roles', 'committee_leaders', 'volunteers', 'volunteer_private',
          'volunteer_hr', 'participations', 'schedule_slots']
ROLES = {'أدمن': 'admin', 'ليدر نشاط': 'activity_leader', 'HR': 'hr', 'تنظيم': 'organizer'}
EMPTY = {'', '-', '--', '.', '..', '...', '....', 'لا يوجد', 'لا'}

report = {'fixed': [], 'dropped': [], 'counts': {}}


def note(kind, msg):
    report[kind].append(msg)


def text(v):
    if v is None:
        return None
    if isinstance(v, float) and v.is_integer():
        v = int(v)
    s = str(v).strip()
    return None if s in EMPTY else s


def digits(v):
    s = text(v)
    if s is None:
        return None
    s = re.sub(r'\D', '', s)
    return s or None


def phone(v, where):
    s = digits(v)
    if s is None:
        return None
    if len(s) == 10 and s.startswith('1'):
        s = '0' + s
    if s.startswith('20') and len(s) == 12:
        s = '0' + s[2:]
    if not re.fullmatch(r'01\d{9}', s):
        note('fixed', f'{where}: phone "{v}" kept as written (not 11 digits)')
    return s


def national_id(v, where):
    s = digits(v)
    if s is None:
        return None
    if not re.fullmatch(r'[23]\d{13}', s):
        note('fixed', f'{where}: national id "{v}" kept as written (not 14 digits)')
    return s


def date(v):
    if v is None or v == '':
        return None
    if isinstance(v, dt.datetime):
        return v.date()
    if isinstance(v, dt.date):
        return v
    s = str(v).strip()
    for fmt in ('%Y-%m-%d', '%d/%m/%Y', '%m/%d/%Y', '%Y-%m-%d %H:%M:%S'):
        try:
            return dt.datetime.strptime(s, fmt).date()
        except ValueError:
            pass
    return None


def timestamp(v):
    if isinstance(v, dt.datetime):
        return v
    d = date(v)
    return dt.datetime.combine(d, dt.time()) if d else None


def clock(v):
    if isinstance(v, dt.time):
        return v
    if isinstance(v, dt.datetime):
        return v.time()
    s = text(v)
    if s and re.fullmatch(r'\d{1,2}:\d{2}(:\d{2})?', s):
        return dt.time(*map(int, s.split(':')))
    return None


def boolean(v):
    if isinstance(v, bool):
        return v
    return str(v).strip().upper() in ('TRUE', '1', 'YES', 'نعم', 'Y')


def parse_nid(nid):
    if not nid or not re.fullmatch(r'[23]\d{13}', nid):
        return None, None
    try:
        born = dt.date((1900 if nid[0] == '2' else 2000) + int(nid[1:3]), int(nid[3:5]), int(nid[5:7]))
    except ValueError:
        born = None
    return born, ('ذكر' if int(nid[12]) % 2 else 'أنثى')


def q(v):
    """SQL literal."""
    if v is None:
        return 'null'
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, (dt.date, dt.datetime, dt.time)):
        return "'" + v.isoformat() + "'"
    return "'" + str(v).replace("'", "''") + "'"


def rows(ws):
    header = [c.value for c in ws[1]]
    for i, r in enumerate(ws.iter_rows(min_row=2, values_only=True), start=2):
        if all(c in (None, '') for c in r):
            continue
        yield i, dict(zip(header, r))


def values(table, cols, data, conflict='', chunk=250):
    if not data:
        return []
    stmts = []
    for start in range(0, len(data), chunk):
        part = data[start:start + chunk]
        out = [f'insert into public.{table} ({", ".join(cols)}) values']
        out.append(',\n'.join('  (' + ', '.join(q(r[c]) for c in cols) + ')' for r in part))
        stmts.append('\n'.join(out) + (f'\n{conflict}' if conflict else '') + ';\n')
    return stmts


def main(src, dst):
    wb = openpyxl.load_workbook(src, data_only=True)
    head = ['-- Generated by scripts/sheet_to_sql.py — do not edit by hand.',
           'begin;',
           '-- History is loaded without notifications or audit rows.',
           *[f'alter table public.{t} disable trigger user;' for t in TABLES],
           '-- Old sheet values are loaded as they are; format checks apply to new edits only.',
           'alter table public.volunteers drop constraint volunteers_phone_format, drop constraint volunteers_whatsapp_format;',
           'alter table public.volunteer_private drop constraint national_id_format;', '']
    sql = []

    # ---------- lookups ----------
    lookups = []
    for n, (i, r) in enumerate(rows(wb['Lookups'])):
        lst, val = text(r.get('القائمة')), text(r.get('القيمة'))
        if lst and val:
            lookups.append({'list': lst, 'value': val, 'parent': text(r.get('الأب')), 'sort_order': n})
    sql.extend(values('lookups', ['list', 'value', 'parent', 'sort_order'], lookups,
                      'on conflict on constraint lookups_unique do nothing'))

    # ---------- staff ----------
    staff = []
    for i, r in rows(wb['HR_Users']):
        email = text(r.get('Email'))
        title = text(r.get('المسمى')) or text(r.get('الدور'))
        role = ROLES.get(title)
        if not email or not role:
            note('dropped', f'HR_Users row {i}: email "{email}" / role "{title}" not usable')
            continue
        staff.append({'email': email.lower(), 'full_name': text(r.get('الاسم')) or email, 'role': role})
    sql.extend(values('staff_roles', ['email', 'full_name', 'role'], staff, 'on conflict do nothing'))

    leaders = []
    for i, r in rows(wb['Committee_Leaders']):
        email, committee = text(r.get('Email')), text(r.get('اللجنة'))
        if email and committee:
            leaders.append({'email': email.lower(), 'committee': committee,
                            'full_name': text(r.get('الاسم')) or email})
    sql.extend(values('committee_leaders', ['email', 'committee', 'full_name'], leaders,
                      'on conflict do nothing'))

    # ---------- volunteers ----------
    vols, privs, hrs, ids, emails = [], [], [], {}, set()
    max_code = 0
    for i, r in rows(wb['Volunteers']):
        code = text(r.get('ID'))
        name = text(r.get('الاسم'))
        if not code or not name:
            note('dropped', f'Volunteers row {i}: no code or name')
            continue
        where = f'{code}'
        vid = str(uuid.uuid5(uuid.NAMESPACE_URL, 'volunteer/' + code))
        ids[code] = vid
        m = re.fullmatch(r'V(\d+)', code)
        if m:
            max_code = max(max_code, int(m.group(1)))

        email = text(r.get('Email'))
        if email:
            email = email.lower()
            if '@' not in email:
                note('fixed', f'{where}: email "{email}" removed (not an email)')
                email = None
            elif email in emails:
                note('fixed', f'{where}: email "{email}" removed (already used by another volunteer)')
                email = None
            else:
                emails.add(email)

        nid = national_id(r.get('الرقم القومي'), where)
        born, gender = parse_nid(nid)
        status = text(r.get('حالة المتطوع')) or 'تحت المتابعة'
        if status not in STATUSES:
            note('fixed', f'{where}: status "{status}" → تحت المتابعة')
            status = 'تحت المتابعة'
        acceptance = text(r.get('حالة القبول'))  # blank stays blank: no grade yet
        if acceptance is not None and acceptance not in ACCEPTANCE:
            note('fixed', f'{where}: acceptance "{acceptance}" left blank (unknown value)')
            acceptance = None
        ph = phone(r.get('رقم الهاتف'), where)

        vols.append({
            'id': vid, 'code': code, 'full_name_ar': name, 'full_name_en': text(r.get('الاسم بالإنجليزية')),
            'phone': ph, 'whatsapp': phone(r.get('رقم الواتساب'), where) or ph, 'email': email,
            'qualification': text(r.get('المؤهل الدراسي')), 'job': text(r.get('الوظيفة')),
            'area': text(r.get('المنطقة السكنية')), 'availability_notes': text(r.get('المواعيد المتاحة')),
            'referral_source': text(r.get('عرفنا منين')),
            'birth_date': born or date(r.get('تاريخ الميلاد')), 'gender': gender or text(r.get('النوع')),
            'registered_at': timestamp(r.get('تاريخ الاستمارة')) or dt.datetime(2022, 1, 1),
            'status': status, 'main_committee': text(r.get('اللجنة الأساسية')),
            'sub_committee': text(r.get('اللجنة الفرعية')),
            'contacted': boolean(r.get('تم التواصل')), 'passed_committee_test': boolean(r.get('اجتاز الاختبار')),
            'joined_group': boolean(r.get('دخل الجروب')), 'is_active': boolean(r.get('فعال')),
            'bought_tshirt': boolean(r.get('اشترى التيشيرت')), 'attended_minicamp': boolean(r.get('حضر الكامب')),
            'minicamp_date': date(r.get('تاريخ الكامب')), 'updated_by': text(r.get('آخر تعديل بواسطة')),
        })
        if vols[-1]['gender'] not in (None, 'ذكر', 'أنثى'):
            vols[-1]['gender'] = None
        privs.append({'volunteer_id': vid, 'national_id': nid})
        hrs.append({'volunteer_id': vid, 'acceptance': acceptance, 'interview_date': date(r.get('تاريخ المقابلة')),
                    'interviewer': text(r.get('القائم على المقابلة')), 'hr_notes': text(r.get('ملاحظات')),
                    'status_changed_at': timestamp(r.get('تاريخ تحديث الحالة'))})

    vcols = list(vols[0].keys())
    sql.extend(values('volunteers', vcols, vols))
    sql.extend(values('volunteer_private', ['volunteer_id', 'national_id'], privs))
    sql.extend(values('volunteer_hr', ['volunteer_id', 'acceptance', 'interview_date', 'interviewer', 'hr_notes',
                                       'status_changed_at'], hrs))
    sql.append(f"select setval('public.volunteer_code_seq', greatest({max_code}, (select last_value from public.volunteer_code_seq)));\n")

    # ---------- participations ----------
    parts = []
    for i, r in rows(wb['Followups']):
        code, vcode = text(r.get('ID')), text(r.get('المتطوع'))
        d, event = date(r.get('التاريخ')), text(r.get('الحدث'))
        if vcode not in ids or not d:
            note('dropped', f'Followups {code or i}: volunteer "{vcode}" or date missing')
            continue
        if not event:
            event = 'أحداث أخرى'
            note('fixed', f'Followups {code}: no event → أحداث أخرى (still counts as a participation)')
        status = REQUEST.get(text(r.get('حالة الطلب')) or 'مقبول', 'accepted')
        beneficiaries = digits(r.get('عدد المستفيدين'))
        parts.append({
            'legacy_code': code, 'volunteer_id': ids[vcode], 'activity_date': d, 'event': event,
            'subject': text(r.get('نوع الحدث')), 'place': text(r.get('المكان')), 'grade': text(r.get('السنة الدراسية')),
            'beneficiaries': int(beneficiaries) if beneficiaries and int(beneficiaries) > 0 else None,
            'notes': text(r.get('ملاحظات')), 'status': status,
            'method': 'individual' if (text(r.get('طريقة التسجيل')) or 'فرد') == 'فرد' else 'group',
            'created_by': text(r.get('سجّله')), 'created_at': timestamp(r.get('وقت الإدخال')) or timestamp(d),
        })
    seen = {}
    unique_parts = []
    for p in parts:
        key = (p['volunteer_id'], p['activity_date'], p['event'], p['subject'] or '', p['grade'] or '')
        if p['status'] != 'rejected' and key in seen:
            note('dropped', f"Followups {p['legacy_code']}: duplicate of {seen[key]} (same volunteer, day, event, subject, grade)")
            continue
        seen[key] = p['legacy_code']
        unique_parts.append(p)
    parts = unique_parts
    pcols = list(parts[0].keys())
    sql.extend(values('participations', pcols, parts,
                      "on conflict (volunteer_id, activity_date, event, coalesce(subject, ''), coalesce(grade, ''))\n"
                      "  where status <> 'rejected' do nothing"))

    # ---------- schedule ----------
    slots = []
    for i, r in rows(wb['Schedule']):
        day, starts, ends = text(r.get('اليوم')), clock(r.get('من')), clock(r.get('إلى'))
        if day not in DAYS or not starts or not ends or ends <= starts:
            note('dropped', f'Schedule {text(r.get("ID")) or i}: day/time not usable')
            continue
        vcode = text(r.get('المتطوع'))
        slots.append({'legacy_code': text(r.get('ID')), 'day': day, 'grade': text(r.get('السنة الدراسية')) or '-',
                      'subject': text(r.get('المادة')) or '-', 'teacher_name': text(r.get('المدرس')),
                      'volunteer_id': ids.get(vcode), 'starts_at': starts, 'ends_at': ends})
    sql.extend(values('schedule_slots', list(slots[0].keys()) if slots else [], slots))

    # ---------- settings ----------
    link = next((text(r.get('القيمة')) for _, r in rows(wb['Lookups']) if text(r.get('القائمة')) == 'لينك الجروب'), None)
    sql.extend(values('app_settings', ['key', 'value'], [{'key': 'whatsapp_group_link', 'value': link}],
                      'on conflict (key) do nothing'))

    tail = []
    tail.append("alter table public.volunteers\n"
               "  add constraint volunteers_phone_format check (phone ~ '^01[0-9]{9}$') not valid,\n"
               "  add constraint volunteers_whatsapp_format check (whatsapp ~ '^01[0-9]{9}$') not valid;")
    tail.append("alter table public.volunteer_private\n"
               "  add constraint national_id_format check (national_id ~ '^[23][0-9]{13}$') not valid;")
    tail.extend(f'alter table public.{t} enable trigger user;' for t in TABLES)
    tail.append('commit;\n')
    with open(dst, 'w', encoding='utf-8') as f:
        f.write('\n'.join(head + sql + tail))
    write_parts(dst, head, sql, tail)

    report['counts'] = {'lookups': len(lookups), 'staff_roles': len(staff), 'committee_leaders': len(leaders),
                        'volunteers': len(vols), 'participations_in_sheet': len(parts), 'schedule_slots': len(slots)}
    with open(dst.rsplit('.', 1)[0] + '_report.json', 'w', encoding='utf-8') as f:
        json.dump(report, f, ensure_ascii=False, indent=2, default=str)
    print(json.dumps(report['counts'], ensure_ascii=False))
    print(f"fixed: {len(report['fixed'])}, dropped: {len(report['dropped'])}")


def write_parts(dst, head, stmts, tail, limit=600_000):
    """Same SQL split into self-contained parts for the Supabase SQL Editor."""
    import os
    out_dir = os.path.join(os.path.dirname(dst), 'parts')
    os.makedirs(out_dir, exist_ok=True)
    for f in os.listdir(out_dir):
        os.remove(os.path.join(out_dir, f))
    wrap = lambda body: '\n'.join(head + body + tail)
    parts, cur = [], []
    for st in stmts:
        if cur and len(wrap(cur + [st]).encode()) > limit:
            parts.append(cur)
            cur = []
        cur.append(st)
    parts.append(cur)
    for i, body in enumerate(parts, 1):
        with open(os.path.join(out_dir, f'part_{i}_of_{len(parts)}.sql'), 'w', encoding='utf-8') as f:
            f.write(wrap(body))


if __name__ == '__main__':
    main(*sys.argv[1:3])
